#!/usr/bin/env node
// Writes data/prompt-meta.json: how well-known each prompt's answers are, so the game can build dives with a fair
// difficulty curve ("easy" prompts where most people can name something, "hard" where only fans can).
// fame = median Wikipedia-language count of the 10 best-known answers (log scale); letter packs inherit their base pack.
// Offline: reads the linked store (or loose packs). Usage: node scripts/build-prompt-meta.mjs
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { readAnyPrompt } from './linked-store.mjs';
const manifest = JSON.parse(await readFile('data/manifest.json', 'utf8'));
const files = Object.keys(manifest.packs).map(id => id + '.json');
const rows = [];
for (const f of files) {
  const id = f.slice(0, -5), items = await readAnyPrompt(manifest, id);
  // "known" = answers that exist in 20+ Wikipedia languages: a rough count of things an ordinary player could name.
  const known = items.filter(i => (+i.s || 0) >= 20).length;
  rows.push({ id, n: items.length, known });
}
// level: 3 easy (plenty of well-known answers), 2 medium, 1 hard, 0 = not served in dives (too few answers a player
// could plausibly name, so most correct-sounding answers would be rejected). Themed packs may still use level 0.
const levelOf = r => {
  // A small CLOSED set whose members are all well known (South American countries, the planets) is fine to serve.
  if (r.n >= 8 && r.n < 30 && r.known / r.n >= 0.8) return 2;
  if (r.n < 30 || (r.n < 80 && r.known < 6)) return 0;
  return r.known < 50 ? 1 : r.known < 200 ? 2 : 3;
};
const out = { note: 'Generated by scripts/build-prompt-meta.mjs. level: 3 easy, 2 medium, 1 hard, 0 = too thin to serve in dives.', prompts: {} };
// Curated prompts carry a hand-set level in data/curated (3 easy, 2 medium, 1 hard).
for (const r of rows) out.prompts[r.id] = { known: r.known, level: manifest.packs[r.id]?.level ?? levelOf(r), n: r.n };
await writeFile('data/prompt-meta.json', JSON.stringify(out));
const dist = [0, 0, 0, 0]; for (const r of Object.values(out.prompts)) dist[r.level]++;
console.log('levels [0..3]', dist);
const zero = rows.filter(r => levelOf(r) === 0).map(r => r.id).filter(id => !/-starts-/.test(id));
console.log('NOT SERVED (base prompts):', zero.length, zero.join(' '));
